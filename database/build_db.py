#!/usr/bin/env python3
"""Build the SQLite data tier from the generated CSVs and export a SQL seed file.

Usage: python database/build_db.py output            (matrix excluded from seed.sql to keep it small)
       python database/build_db.py output --full-seed  (include every table in seed.sql)
"""
import csv, os, sqlite3, sys

src = sys.argv[1] if len(sys.argv) > 1 else "output"
full = "--full-seed" in sys.argv
here = os.path.dirname(os.path.abspath(__file__))
db_path = os.path.join(src, "delivery_routing.db")
# parents before children, so foreign keys are satisfied during load
ORDER = ["customer_sites", "orders", "deliveries", "time_windows", "vehicles", "vehicle_capacity", "drivers",
         "shifts", "travel_time_matrix", "routes", "route_stops", "delivery_outcomes", "delivery_events"]

if os.path.exists(db_path):
    os.remove(db_path)
con = sqlite3.connect(db_path)
con.executescript(open(os.path.join(here, "schema.sql")).read())
for t in ORDER:
    with open(os.path.join(src, "data", f"{t}.csv"), newline="") as f:
        rd = csv.reader(f)
        cols = next(rd)
        sql = f"INSERT INTO {t} ({','.join(cols)}) VALUES ({','.join('?' * len(cols))})"
        con.executemany(sql, ([v if v != "" else None for v in row] for row in rd))
con.commit()

bad = con.execute("PRAGMA foreign_key_check").fetchall()
print("Foreign key violations:", len(bad))
for t in ORDER:
    print(f"  {t:22s} {con.execute(f'SELECT COUNT(*) FROM {t}').fetchone()[0]:>8} rows")

seed_path = os.path.join(here, "seed.sql")
skip = set() if full else {"travel_time_matrix"}
with open(seed_path, "w") as out:
    out.write("-- Seed data generated by backend/generate.py (seed 20261022). Load after schema.sql.\n")
    if skip:
        out.write("-- travel_time_matrix omitted (123k rows); it is in data/travel_time_matrix.csv "
                  "or run build_db.py with --full-seed.\n")
    out.write("PRAGMA foreign_keys = OFF;\nBEGIN TRANSACTION;\n")
    for line in con.iterdump():
        if line.startswith("INSERT INTO"):
            table = line.split('"')[1]
            if table not in skip:
                out.write(line + "\n")
    out.write("COMMIT;\nPRAGMA foreign_keys = ON;\n")
print("Wrote", db_path, "and", seed_path, f"({os.path.getsize(seed_path) // 1024} KB)")
sys.exit(1 if bad else 0)